"""Exact two-parameter filtration and minimal bases for bounded trace relations.

Phase 30 analyzes the nested family R[L,D] produced by Phase 29:
- FTI substitutions use all words of length at most L;
- trace-monomial multipliers have total matrix-letter degree at most D;
- the maximum length of an individual multiplier trace word is fixed.

For each cell it computes an exact Q-basis, the union of its two immediate
predecessor spaces, and a complement basis for the quotient by that union.
All dependence certificates are recomputed exactly. This is finite filtered
linear algebra, not a claim of minimal generators for the infinite T-ideal.
"""
from __future__ import annotations

from collections import defaultdict
import re

import trace_ideal_closure as phase29


_PAIRED_RE = re.compile(r"(-?)<([0-9A-Z]+)_2\|([0-9A-Z]+)_3>")
_DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def _paired(value: int) -> str:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError("paired integer input must be an integer")
    sign = "-" if value < 0 else ""
    value = abs(value)

    def encode(number: int, base: int) -> str:
        if number == 0:
            return "0"
        out = ""
        while number:
            number, digit = divmod(number, base)
            out = _DIGITS[digit] + out
        return out

    return f"{sign}<{encode(value, 2)}_2|{encode(value, 3)}_3>"


def _integer(value, name: str, minimum: int = 0) -> int:
    result = phase29._integer(value, name, minimum)
    return result


def _decode_pair(value: str, name: str) -> int:
    return phase29._integer(value, name, minimum=None)


def _poly_total_degree(poly) -> int:
    if not poly:
        return 0
    degrees = {
        sum(len(word) for word in trace_monomial)
        for trace_monomial in poly
    }
    if len(degrees) != 1:
        raise ArithmeticError(
            "Phase 30 expected homogeneous trace polynomials; found mixed total word degrees"
        )
    return next(iter(degrees))


def _basis_polynomial(entry):
    poly = phase29._poly_from_terms(entry["trace_terms"])
    if not poly:
        raise ArithmeticError("Phase 29 returned an empty basis vector")
    degree = _poly_total_degree(poly)
    declared_degree = _decode_pair(
        entry["total_matrix_word_degree"],
        "total_matrix_word_degree",
    )
    if degree != declared_degree:
        raise ArithmeticError(
            "Phase 29 basis degree metadata does not match its exact trace polynomial"
        )
    if entry.get("universal_verification", {}).get("status") != "universally_verified_identity":
        raise ArithmeticError("Phase 29 basis vector lacks a universal generic-matrix verification")
    return poly, degree


def _degree_profile(degrees):
    counts = defaultdict(int)
    for degree in degrees:
        counts[degree] += 1
    return {
        _paired(degree): _paired(count)
        for degree, count in sorted(counts.items())
    }


def _certificate_is_exact(certificate, candidate_polynomials) -> bool:
    return phase29._verify_linear_certificate(certificate, candidate_polynomials)


def _certificate_report(certificate):
    return phase29._linear_certificate_report(certificate)


def _insert_checked(basis, poly, candidate_id, polynomials):
    polynomials[candidate_id] = poly
    independent, relation, pivot = phase29._insert_exact_basis(
        basis, poly, candidate_id
    )
    if not independent and not _certificate_is_exact(relation, polynomials):
        raise ArithmeticError(
            f"Phase 30 exact linear-dependency certificate failed for {candidate_id}"
        )
    return independent, relation, pivot


def analyze_bounded_relation_filtration(
    dimension: int,
    generator_count: int = 2,
    max_substitution_word_length: int = 2,
    max_multiplier_trace_word_length: int = 2,
    max_multiplier_total_word_degree: int = 2,
    max_filtration_cells: int = 25,
    max_word_catalog_size: int = 32,
    max_substitution_sets: int = 4096,
    max_multiplier_monomials: int = 256,
    max_derived_relations: int = 5000,
    max_identity_permutations: int = 100_000,
    max_seed_expansion_terms_per_identity: int = 1_000_000,
    max_seed_expansion_terms_per_cell: int = 5_000_000,
    max_relation_expansion_terms_per_relation: int = 1_000_000,
    max_relation_expansion_terms_per_cell: int = 10_000_000,
    max_aggregate_seed_expansion_terms: int = 20_000_000,
    max_aggregate_relation_expansion_terms: int = 40_000_000,
    max_certificate_records: int = 20_000,
):
    """Compute exact bases and quotient increments over a nested (L,D) grid.

    R[L,D] is the Q-span generated by all Phase 28 FTI substitutions on words
    of length <= L, multiplied by all trace monomials whose total matrix-letter
    degree is <= D. The maximum length of each multiplier trace word is fixed
    across the grid. Hence R[L-1,D] and R[L,D-1] are subspaces of R[L,D].

    The reported quotient is R[L,D] / (R[L-1,D] + R[L,D-1]). Its dimension is
    the exact number of new Q-vector-space directions at this filtration cell.
    This is a minimal complement relative to the two predecessor slices only;
    it is not a minimal T-ideal generating set.
    """
    dimension = _integer(dimension, "dimension", 1)
    generator_count = _integer(generator_count, "generator_count", 1)
    max_substitution_word_length = _integer(
        max_substitution_word_length, "max_substitution_word_length", 1
    )
    max_multiplier_trace_word_length = _integer(
        max_multiplier_trace_word_length, "max_multiplier_trace_word_length", 1
    )
    max_multiplier_total_word_degree = _integer(
        max_multiplier_total_word_degree, "max_multiplier_total_word_degree", 0
    )
    max_filtration_cells = _integer(max_filtration_cells, "max_filtration_cells", 1)
    max_word_catalog_size = _integer(max_word_catalog_size, "max_word_catalog_size", 1)
    max_substitution_sets = _integer(max_substitution_sets, "max_substitution_sets", 1)
    max_multiplier_monomials = _integer(max_multiplier_monomials, "max_multiplier_monomials", 1)
    max_derived_relations = _integer(max_derived_relations, "max_derived_relations", 1)
    max_identity_permutations = _integer(max_identity_permutations, "max_identity_permutations", 1)
    max_seed_expansion_terms_per_identity = _integer(
        max_seed_expansion_terms_per_identity,
        "max_seed_expansion_terms_per_identity",
        1,
    )
    max_seed_expansion_terms_per_cell = _integer(
        max_seed_expansion_terms_per_cell, "max_seed_expansion_terms_per_cell", 1
    )
    max_relation_expansion_terms_per_relation = _integer(
        max_relation_expansion_terms_per_relation,
        "max_relation_expansion_terms_per_relation",
        1,
    )
    max_relation_expansion_terms_per_cell = _integer(
        max_relation_expansion_terms_per_cell,
        "max_relation_expansion_terms_per_cell",
        1,
    )
    max_aggregate_seed_expansion_terms = _integer(
        max_aggregate_seed_expansion_terms,
        "max_aggregate_seed_expansion_terms",
        1,
    )
    max_aggregate_relation_expansion_terms = _integer(
        max_aggregate_relation_expansion_terms,
        "max_aggregate_relation_expansion_terms",
        1,
    )
    max_certificate_records = _integer(
        max_certificate_records, "max_certificate_records", 1
    )

    cell_count = max_substitution_word_length * (
        max_multiplier_total_word_degree + 1
    )
    configuration = {
        "schema": "universe.trace-relation-filtration.v1",
        "dimension": _paired(dimension),
        "generator_count": _paired(generator_count),
        "max_substitution_word_length": _paired(max_substitution_word_length),
        "max_multiplier_trace_word_length": _paired(max_multiplier_trace_word_length),
        "max_multiplier_total_word_degree": _paired(max_multiplier_total_word_degree),
        "coefficient_field": "Q",
        "filtration": {
            "substitution_bound": "L: all nonempty matrix words of length <= L",
            "multiplier_bound": "D: all trace-monomial multipliers of total matrix-letter degree <= D",
            "nested_space": "R[L,D]",
            "predecessor_sum": "R[L-1,D] + R[L,D-1]",
        },
        "sampled_matrix_data_used": False,
        "max_filtration_cells": _paired(max_filtration_cells),
        "required_filtration_cells": _paired(cell_count),
    }
    if cell_count > max_filtration_cells:
        return {
            **configuration,
            "status": "unresolved_filtration_cell_cap",
            "cells": [],
            "reason": "the requested rectangular filtration exceeds max_filtration_cells",
        }

    cells = {}
    cell_reports = []
    aggregate_seed_work = 0
    aggregate_relation_work = 0
    certificate_records = 0

    for substitution_bound in range(1, max_substitution_word_length + 1):
        for multiplier_bound in range(max_multiplier_total_word_degree + 1):
            remaining_seed = (
                max_aggregate_seed_expansion_terms - aggregate_seed_work
            )
            remaining_relations = (
                max_aggregate_relation_expansion_terms - aggregate_relation_work
            )
            if remaining_seed <= 0 or remaining_relations <= 0:
                return {
                    **configuration,
                    "status": "partial_filtration_aggregate_budget_unresolved",
                    "cells": cell_reports,
                    "unresolved_cell": {
                        "substitution_bound": _paired(substitution_bound),
                        "multiplier_bound": _paired(multiplier_bound),
                        "reason": "aggregate Phase 28 seed or Phase 29 relation expansion budget exhausted",
                    },
                    "aggregate_work": {
                        "seed_expanded_index_assignments": _paired(aggregate_seed_work),
                        "relation_expanded_index_assignments": _paired(aggregate_relation_work),
                    },
                }

            seed_cap = min(max_seed_expansion_terms_per_cell, remaining_seed)
            relation_cap = min(max_relation_expansion_terms_per_cell, remaining_relations)
            bounded = phase29.build_bounded_trace_relation_space(
                dimension=dimension,
                generator_count=generator_count,
                max_substitution_word_length=substitution_bound,
                max_multiplier_trace_word_length=max_multiplier_trace_word_length,
                max_multiplier_total_word_degree=multiplier_bound,
                max_word_catalog_size=max_word_catalog_size,
                max_substitution_sets=max_substitution_sets,
                max_multiplier_monomials=max_multiplier_monomials,
                max_derived_relations=max_derived_relations,
                max_identity_permutations=max_identity_permutations,
                max_seed_expansion_terms_per_identity=max_seed_expansion_terms_per_identity,
                max_seed_total_expansion_terms=seed_cap,
                max_relation_expansion_terms=max_relation_expansion_terms_per_relation,
                max_total_relation_expansion_terms=relation_cap,
            )
            if bounded["status"] not in (
                "complete_bounded_relation_space",
                "complete_empty_bounded_relation_space",
            ):
                return {
                    **configuration,
                    "status": "partial_filtration_cell_unresolved",
                    "cells": cell_reports,
                    "unresolved_cell": {
                        "substitution_bound": _paired(substitution_bound),
                        "multiplier_bound": _paired(multiplier_bound),
                        "phase29_status": bounded["status"],
                        "seed_catalog_status": bounded.get("seed_catalog_status"),
                        "derived_relation_candidate_count": bounded.get(
                            "derived_relation_candidate_count"
                        ),
                        "reason": "Phase 29 did not complete this bounded relation space",
                    },
                    "aggregate_work": {
                        "seed_expanded_index_assignments": _paired(aggregate_seed_work),
                        "relation_expanded_index_assignments": _paired(aggregate_relation_work),
                    },
                }

            seed_work = _decode_pair(
                bounded.get("seed_verification_work", {}).get(
                    "expanded_index_assignments", "<0_2|0_3>"
                ),
                "seed_expanded_index_assignments",
            )
            relation_work = _decode_pair(
                bounded["verification_work"]["expanded_index_assignments"],
                "relation_expanded_index_assignments",
            )
            if seed_work > seed_cap or relation_work > relation_cap:
                raise ArithmeticError("Phase 29 reported work beyond its supplied Phase 30 budget")
            aggregate_seed_work += seed_work
            aggregate_relation_work += relation_work

            current_basis = bounded["independent_basis"]
            current_rank = _decode_pair(
                bounded["independent_basis_count"], "independent_basis_count"
            )
            if current_rank != len(current_basis):
                raise ArithmeticError("Phase 29 basis count does not match returned basis vectors")

            predecessors = []
            if substitution_bound > 1:
                predecessors.append(
                    (f"L{substitution_bound - 1}:D{multiplier_bound}",
                     cells[(substitution_bound - 1, multiplier_bound)])
                )
            if multiplier_bound > 0:
                predecessors.append(
                    (f"L{substitution_bound}:D{multiplier_bound - 1}",
                     cells[(substitution_bound, multiplier_bound - 1)])
                )

            lower_basis = []
            lower_polynomials = {}
            lower_degrees = []
            overlap_certificates = []
            for predecessor_label, predecessor in predecessors:
                for basis_index, entry in enumerate(predecessor["basis_entries"]):
                    candidate_id = (
                        f"LOWER-{predecessor_label}-B{basis_index:05d}"
                    )
                    poly, degree = _basis_polynomial(entry)
                    independent, relation, _ = _insert_checked(
                        lower_basis, poly, candidate_id, lower_polynomials
                    )
                    if independent:
                        lower_degrees.append(degree)
                    else:
                        overlap_certificates.append({
                            "candidate_id": candidate_id,
                            "source_slice": predecessor_label,
                            "status": "exactly_dependent_in_predecessor_union",
                            "linear_dependency_certificate": _certificate_report(relation),
                            "recomputed_residual": "0",
                        })
                        certificate_records += 1

            lower_union_rank = len(lower_basis)
            combined_basis = list(lower_basis)
            combined_polynomials = dict(lower_polynomials)
            new_directions = []
            quotient_certificates = []
            current_degrees = []
            for basis_index, entry in enumerate(current_basis):
                candidate_id = (
                    f"CURRENT-L{substitution_bound}-D{multiplier_bound}-B{basis_index:05d}"
                )
                poly, degree = _basis_polynomial(entry)
                independent, relation, pivot = _insert_checked(
                    combined_basis, poly, candidate_id, combined_polynomials
                )
                current_degrees.append(degree)
                if independent:
                    new_directions.append({
                        "candidate_id": candidate_id,
                        "phase29_candidate_id": entry["candidate_id"],
                        "seed_identity_id": entry["seed_identity_id"],
                        "multiplier_label": entry["multiplier_label"],
                        "total_matrix_word_degree": _paired(degree),
                        "pivot_trace_monomial": phase29._trace_monomial_label(pivot),
                        "trace_terms": entry["trace_terms"],
                        "universal_verification": entry["universal_verification"],
                    })
                else:
                    quotient_certificates.append({
                        "candidate_id": candidate_id,
                        "status": "already_in_predecessor_union_plus_prior_new_directions",
                        "linear_dependency_certificate": _certificate_report(relation),
                        "recomputed_residual": "0",
                    })
                    certificate_records += 1

            if certificate_records > max_certificate_records:
                return {
                    **configuration,
                    "status": "partial_filtration_certificate_cap_unresolved",
                    "cells": cell_reports,
                    "unresolved_cell": {
                        "substitution_bound": _paired(substitution_bound),
                        "multiplier_bound": _paired(multiplier_bound),
                    },
                    "aggregate_work": {
                        "seed_expanded_index_assignments": _paired(aggregate_seed_work),
                        "relation_expanded_index_assignments": _paired(aggregate_relation_work),
                    },
                    "certificate_records": _paired(certificate_records),
                }

            quotient_rank = len(new_directions)
            if lower_union_rank + quotient_rank != current_rank:
                raise ArithmeticError(
                    "Phase 30 quotient rank does not reconcile with the Phase 29 relation-space dimension"
                )
            if lower_union_rank > current_rank:
                raise ArithmeticError("A predecessor relation space is not contained in the current slice")

            left_rank = (
                _decode_pair(predecessors[0][1]["relation_space_dimension"], "left predecessor rank")
                if substitution_bound > 1 else 0
            )
            bottom_rank = (
                _decode_pair(predecessors[-1][1]["relation_space_dimension"], "bottom predecessor rank")
                if multiplier_bound > 0 else 0
            )
            if substitution_bound > 1 and multiplier_bound > 0:
                # The first predecessor is L-1,D; the second is L,D-1.
                left_rank = _decode_pair(
                    cells[(substitution_bound - 1, multiplier_bound)]["relation_space_dimension"],
                    "left predecessor rank",
                )
                bottom_rank = _decode_pair(
                    cells[(substitution_bound, multiplier_bound - 1)]["relation_space_dimension"],
                    "bottom predecessor rank",
                )
            intersection_rank = left_rank + bottom_rank - lower_union_rank
            if intersection_rank < 0:
                raise ArithmeticError("Computed predecessor intersection dimension is negative")

            rank_profile = _degree_profile(current_degrees)
            lower_profile = _degree_profile(lower_degrees)
            quotient_profile = _degree_profile(
                _decode_pair(item["total_matrix_word_degree"], "new direction degree")
                for item in new_directions
            )
            if sum(_decode_pair(v, "rank profile count") for v in rank_profile.values()) != current_rank:
                raise ArithmeticError("Current graded rank profile does not sum to relation-space rank")
            if sum(_decode_pair(v, "lower profile count") for v in lower_profile.values()) != lower_union_rank:
                raise ArithmeticError("Lower graded rank profile does not sum to predecessor-union rank")
            if sum(_decode_pair(v, "quotient profile count") for v in quotient_profile.values()) != quotient_rank:
                raise ArithmeticError("Quotient graded rank profile does not sum to quotient dimension")

            cell = {
                "substitution_bound": _paired(substitution_bound),
                "multiplier_bound": _paired(multiplier_bound),
                "status": bounded["status"],
                "relation_space_dimension": _paired(current_rank),
                "predecessor_left_dimension": _paired(left_rank),
                "predecessor_bottom_dimension": _paired(bottom_rank),
                "predecessor_union_dimension": _paired(lower_union_rank),
                "predecessor_intersection_dimension": _paired(intersection_rank),
                "new_quotient_dimension": _paired(quotient_rank),
                "rank_by_total_word_degree": rank_profile,
                "predecessor_union_rank_by_total_word_degree": lower_profile,
                "new_quotient_rank_by_total_word_degree": quotient_profile,
                "basis_entries": current_basis,
                "new_directions": new_directions,
                "overlap_certificates": overlap_certificates,
                "quotient_dependency_certificates": quotient_certificates,
                "phase29_counts": {
                    "seed_identity_count": bounded["seed_identity_count"],
                    "seed_candidate_substitution_sets": bounded["seed_candidate_substitution_sets"],
                    "multiplier_monomial_count": bounded["multiplier_monomial_count"],
                    "derived_relation_candidate_count": bounded["derived_relation_candidate_count"],
                    "exactly_dependent_count": bounded["exactly_dependent_count"],
                },
                "verification_work": {
                    "seed_expanded_index_assignments": _paired(seed_work),
                    "relation_expanded_index_assignments": _paired(relation_work),
                },
                "basis_minimality": {
                    "field": "Q",
                    "basis_cardinality": _paired(current_rank),
                    "rank": _paired(current_rank),
                    "minimality_scope": "minimum cardinality among Q-vector-space bases of this finite bounded relation space",
                    "not_an_ideal_generator_minimality_claim": True,
                },
            }
            cells[(substitution_bound, multiplier_bound)] = cell
            cell_reports.append(cell)

    stability = {}
    if max_substitution_word_length >= 2:
        for multiplier_bound in range(max_multiplier_total_word_degree + 1):
            last = cells[(max_substitution_word_length, multiplier_bound)]
            previous = cells[(max_substitution_word_length - 1, multiplier_bound)]
            delta_last = (
                _decode_pair(last["relation_space_dimension"], "rank")
                - _decode_pair(previous["relation_space_dimension"], "rank")
            )
            stability[_paired(multiplier_bound)] = {
                "last_word_length_rank_increment": _paired(delta_last),
                "interpretation": (
                    "observed final-step increment only; no inference of stabilization beyond the searched word-length window"
                ),
            }

    return {
        **configuration,
        "status": "complete_bounded_filtration",
        "cells": cell_reports,
        "stability_diagnostic": stability,
        "aggregate_work": {
            "seed_expanded_index_assignments": _paired(aggregate_seed_work),
            "relation_expanded_index_assignments": _paired(aggregate_relation_work),
            "seed_cap": _paired(max_aggregate_seed_expansion_terms),
            "relation_cap": _paired(max_aggregate_relation_expansion_terms),
            "certificate_records": _paired(certificate_records),
            "certificate_cap": _paired(max_certificate_records),
            "accounting": (
                "Seed and derived-relation generic index assignments are aggregated separately. "
                "They are deterministic work proxies, not wall-clock or coefficient-bit complexity."
            ),
        },
        "minimality_boundary": (
            "Each returned basis is cardinality-minimal as a Q-vector-space basis of its finite R[L,D] slice. "
            "Each quotient complement is minimal relative to R[L-1,D]+R[L,D-1]. "
            "Neither result proves a minimal generating set of the infinite T-ideal."
        ),
        "structural_boundary": (
            "The table is a finite two-parameter filtration and degree profile. "
            "A final-step rank increment is descriptive evidence only; no extrapolation to an infinite Hilbert series, "
            "eventual polynomial, stabilization theorem or full ideal presentation is made."
        ),
    }
